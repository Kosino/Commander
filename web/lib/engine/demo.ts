function padDeck(commander: CardData, seed: CardData[], target = 99): CardData[] {
  const out = [...seed];
  let i = 0;
  while (out.length < target) {
    i += 1;
    out.push(
      card(`${commander.name} Filler ${i}`, 'Creature — Construct', {
        mana_cost: '{2}',
        power: '1',
        toughness: '1',
        colors: [],
        color_identity: commander.color_identity,
      }),
    );
  }
  return out;
}

