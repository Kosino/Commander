function card(
  name: string,
  type_line: string,
  opts: Partial<CardData> & { mana_cost?: string } = {},
): CardData {
  return {
    oracle_id: `demo-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    name,
    type_line,
    mana_cost: opts.mana_cost,
    oracle_text: opts.oracle_text,
    power: opts.power,
    toughness: opts.toughness,
    loyalty: opts.loyalty,
    colors: (opts.colors || []) as ManaColor[],
    color_identity: (opts.color_identity || opts.colors || []) as ManaColor[],
    keywords: opts.keywords || [],
  };
}

